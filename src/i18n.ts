export function systemLanguage(value: string): Language {
  const code = String(value || "").trim().toLowerCase().replace(/[_-].*$/, "");
  if (code === "german" || code === "de") return "de";
  if (["spanish", "latamspanish", "spanishlatam", "spanishlatinamerica", "latam", "es"].includes(code)) return "es";
  if (code === "french" || code === "fr") return "fr";
  if (code === "russian" || code === "ru") return "ru";
  return "en";
}

export function t(lang: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return messages[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
